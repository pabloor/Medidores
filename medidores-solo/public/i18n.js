(function () {
  let saved = null;
  try { saved = localStorage.getItem('medidores:lang'); } catch {}
  const nav = (navigator.language || 'es').slice(0, 2).toLowerCase();
  window.LANG = saved && I18N[saved] ? saved : I18N[nav] ? nav : 'en';
  document.documentElement.lang = window.LANG;

  window.t = function (key, p) {
    const dict = I18N[window.LANG] || I18N.es;
    let s = dict[key] ?? I18N.es[key] ?? key;
    if (p) s = s.replace(/\{(\w+)\}/g, (m, k) => (p[k] != null ? p[k] : m));
    return s;
  };

  // Aplica las traducciones a los elementos marcados en el HTML.
  window.applyI18n = function (root = document) {
    root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
    root.querySelectorAll('[data-i18n-aria]').forEach((el) => el.setAttribute('aria-label', t(el.dataset.i18nAria)));
    root.querySelectorAll('[data-i18n-ph]').forEach((el) => el.setAttribute('placeholder', t(el.dataset.i18nPh)));
    root.querySelectorAll('[data-i18n-alt]').forEach((el) => el.setAttribute('alt', t(el.dataset.i18nAlt)));
    root.querySelectorAll('[data-i18n-title]').forEach((el) => el.setAttribute('title', t(el.dataset.i18nTitle)));
    document.title = t('title');
  };
})();
